#!/usr/bin/env python3
"""Convert a PNG into an L8 (8-bit grayscale) C header for the FT812 display.

Standard library only (no Pillow). Supports non-interlaced 8-bit PNGs
(grayscale, gray+alpha, RGB, RGBA). Alpha is composited over black.

The image is centred on a canvas of --size WxH (black padding), so a smaller
logo can replace the 172x172 boot logo without touching display.cpp.

Usage:
  tools/png_to_l8.py logo.png core/libs/images/poly_logo_172x172_L8.h \
      --name poly_logo_172x172_l8 --size 172x172
"""
import argparse
import struct
import sys
import zlib


def read_png(path):
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("not a PNG")
    pos, idat = 8, b""
    while pos < len(data):
        length, ctype = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if ctype == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
        elif ctype == b"IDAT":
            idat += body
        pos += 12 + length
    if depth != 8 or interlace != 0:
        sys.exit("only 8-bit non-interlaced PNGs are supported")
    channels = {0: 1, 4: 2, 2: 3, 6: 4}.get(color)
    if channels is None:
        sys.exit("palette PNGs are not supported; export as RGB or grayscale")

    raw = zlib.decompress(idat)
    stride = w * channels
    rows, prev, i = [], bytearray(stride), 0
    for _ in range(h):
        ftype = raw[i]
        line = bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - channels] if x >= channels else 0
            b = prev[x]
            c = prev[x - channels] if x >= channels else 0
            if ftype == 1:
                line[x] = (line[x] + a) & 0xFF
            elif ftype == 2:
                line[x] = (line[x] + b) & 0xFF
            elif ftype == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pred) & 0xFF
        rows.append(line)
        prev = line

    gray = []
    for line in rows:
        out = []
        for x in range(w):
            px = line[x * channels:(x + 1) * channels]
            if channels in (1, 2):
                v = px[0]
            else:
                v = round(0.299 * px[0] + 0.587 * px[1] + 0.114 * px[2])
            if channels in (2, 4):
                v = v * px[-1] // 255
            out.append(v)
        gray.append(out)
    return w, h, gray


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("png")
    ap.add_argument("header")
    ap.add_argument("--name", required=True, help="C array name")
    ap.add_argument("--size", required=True, help="canvas WxH, e.g. 172x172")
    args = ap.parse_args()

    cw, ch = (int(n) for n in args.size.lower().split("x"))
    w, h, gray = read_png(args.png)
    if w > cw or h > ch:
        sys.exit(f"image {w}x{h} is larger than canvas {cw}x{ch}")
    ox, oy = (cw - w) // 2, (ch - h) // 2

    pixels = []
    for y in range(ch):
        for x in range(cw):
            inside = ox <= x < ox + w and oy <= y < oy + h
            pixels.append(gray[y - oy][x - ox] if inside else 0)

    total = cw * ch
    with open(args.header, "w") as f:
        f.write(f"/* Generated by tools/png_to_l8.py from {args.png.split('/')[-1]}\n"
                f" * resolution {cw}x{ch}, format L8, stride {cw}, total size {total} */\n")
        f.write(f"const uint8_t {args.name}[] = {{\n")
        for i in range(0, total, 24):
            f.write("    " + " ".join(f"{v:3d}," for v in pixels[i:i + 24]) + "\n")
        f.write("};\n")
    print(f"{w}x{h} -> {cw}x{ch} canvas at offset ({ox},{oy}), {total} bytes -> {args.header}")


if __name__ == "__main__":
    main()
